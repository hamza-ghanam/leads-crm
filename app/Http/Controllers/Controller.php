class Controller extends BaseController
{
    use AuthorizesRequests, DispatchesJobs, ValidatesRequests;

    public function hasPermission($permission): bool
    {
        if (!auth()->user()->hasPermissionTo($permission)) {
            abort(404);
        }

        return true;
    }
}
