 * )
 *
 * @OA\SecurityScheme(
 *     securityScheme="sanctum",
 *     type="http",
 *     scheme="bearer",
 *     bearerFormat="JWT",
 *     in="header",
 *     name="Authorization"
 * )
 *
 * @OA\Parameter(
 *      parameter = "CorrelationId",
 *      name = "X-Correlation-ID",
 *      in = "header",
