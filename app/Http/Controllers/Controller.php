 *      @OA\Schema(type = "string", example = "3f2c8c8e-1a34-4a0e-9c7b-0f2d2e7c4b91")
 *  )
 *
 * @OA\Schema(
 *      schema="ApiError",
 *      type="object",
 *      description="Standard API error response",
 *      @OA\Property(
 *          property="success",
 *          type="boolean",
 *          example=false
 *      ),
 *      @OA\Property(
